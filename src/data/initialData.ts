// Helper to generate realistic 24-point history (hourly over last 24h)
function generateHistory(baseValue: number, jitter: number, unit: string) {
  const points = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const t = now - i * 3600 * 1000;
    const val = Number((baseValue + (Math.sin(i * 0.4) * jitter) + (Math.random() * jitter * 0.5)).toFixed(2));
    points.push({
      timestamp: t,
      value: Math.max(0, val),
      unit,
      rateOfChange: Number((jitter * 0.1).toFixed(3)),
    });
  }
  return points;
}

